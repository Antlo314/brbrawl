// Writes assets.js: the list of every art and sound file in the game, so the game only asks for files that exist.
// (Without it, each battler outfit fired ~55 requests for optional frames that mostly aren't there.)
// Run after adding or removing art:  node make-assets.js   (serve.js always serves a fresh list; build.bat runs this too)
const fs = require('fs'), path = require('path');
const root = __dirname, DIRS = ['sprites', 'sprites-hd', 'art', 'audio'];

function list() {
  const out = [];
  const walk = d => {
    for (const e of fs.readdirSync(path.join(root, d), { withFileTypes: true })) {
      const p = `${d}/${e.name}`;
      if (e.isDirectory()) walk(p); else if (/\.(jpg|jpeg|png|webp|mp3|ogg|wav|m4a)$/i.test(e.name)) out.push(p);
    }
  };
  for (const d of DIRS) if (fs.existsSync(path.join(root, d))) walk(d);
  return out.sort();
}
const source = () => `// Generated by make-assets.js: every art and sound file in the game. Rebuild with  node make-assets.js\nwindow.ASSETS = ${JSON.stringify(list())};\n`;

module.exports = source;
if (require.main === module) {
  const s = source();
  fs.writeFileSync(path.join(root, 'assets.js'), s);
  console.log(`assets.js: ${JSON.parse(s.slice(s.indexOf('['), s.lastIndexOf(']') + 1)).length} files`);
}
